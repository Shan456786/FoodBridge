#!/usr/bin/env node
// Database helper.
//
//   node scripts/db.mjs bundle    -> writes supabase/setup.sql (paste into the Supabase SQL editor)
//   node scripts/db.mjs migrate   -> applies pending migrations using DATABASE_URL
//
// DATABASE_URL is the Postgres connection string from Supabase
// (Project Settings → Database → Connection string → Session pooler).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { config } from 'dotenv'

config({ path: '.env.local', quiet: true })
config({ quiet: true })

const dir = path.resolve('supabase/migrations')
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
const cmd = process.argv[2]

if (cmd === 'bundle') {
  const out = [
    '-- FoodBridge: all migrations in order. Generated by `npm run db:bundle` — do not edit.',
    '-- Paste into Supabase Dashboard → SQL Editor → Run (on a fresh project).',
    '',
    ...files.map((f) => `-- ===== ${f} =====\n${readFileSync(path.join(dir, f), 'utf8')}`),
  ].join('\n')
  writeFileSync('supabase/setup.sql', out)
  console.log(`Wrote supabase/setup.sql (${files.length} migrations)`)
} else if (cmd === 'migrate') {
  const url = process.env.DATABASE_URL
  if (!url) {
    console.error('Set DATABASE_URL in .env.local (Supabase → Project Settings → Database → Session pooler URI).')
    process.exit(1)
  }
  const { default: postgres } = await import('postgres')
  const sql = postgres(url, { ssl: 'require', max: 1, onnotice: () => {} })
  try {
    await sql`create schema if not exists foodbridge_meta`
    await sql`create table if not exists foodbridge_meta.applied_migrations (name text primary key, applied_at timestamptz not null default now())`
    const applied = new Set((await sql`select name from foodbridge_meta.applied_migrations`).map((r) => r.name))
    for (const f of files) {
      if (applied.has(f)) {
        console.log(`· ${f} (already applied)`)
        continue
      }
      await sql.begin(async (tx) => {
        await tx.unsafe(readFileSync(path.join(dir, f), 'utf8'))
        await tx`insert into foodbridge_meta.applied_migrations (name) values (${f})`
      })
      console.log(`✓ ${f}`)
    }
  } finally {
    await sql.end()
  }
} else {
  console.log('Usage: node scripts/db.mjs <bundle|migrate>')
  process.exit(1)
}
